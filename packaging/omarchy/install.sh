#!/usr/bin/env bash
# Installs oma-plexo as an Omarchy plugin: Plexo's engine as a headless daemon
# running as a user service, `plexo-ctl` on PATH, and the bar widget + panel
# into the shell.
#
#   packaging/omarchy/install.sh [plexo-dir]
#
# Idempotent: run it again after `git pull` to update everything. Undo with
# packaging/omarchy/uninstall.sh.
set -euo pipefail

PLEXO_DIR="${1:-$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)}"
PLUGIN_ID="omega.oma-plexo"
PLUGIN_SRC="$PLEXO_DIR/packaging/omarchy/plugin"
PLUGIN_DST="$HOME/.config/omarchy/plugins/$PLUGIN_ID"
UNIT_NAME="plexo-daemon.service"
UNIT_DIR="$HOME/.config/systemd/user"
CTL="$HOME/.local/bin/plexo-ctl"

say() { printf '%s\n' "$*"; }

if ! command -v node >/dev/null 2>&1; then
  say "node is not on PATH. Install it first (omarchy pkg add nodejs)."
  exit 1
fi
NODE="$(command -v node)"

say "Plexo source: $PLEXO_DIR"

# 1. The daemon build ---------------------------------------------------------
if [[ ! -f "$PLEXO_DIR/out/daemon/app/daemon/index.js" || "${PLEXO_REBUILD:-1}" == "1" ]]; then
  say "Building the daemon…"
  (cd "$PLEXO_DIR" && npm run --silent build:daemon >/dev/null)
fi

# 2. plexo-ctl, on PATH --------------------------------------------------------
mkdir -p "$(dirname "$CTL")"
cat >"$CTL" <<EOF
#!/bin/sh
# Generated by oma-plexo (packaging/omarchy/install.sh) — talks to the Plexo daemon.
exec "$NODE" "$PLEXO_DIR/out/daemon/app/daemon/ctl.js" "\$@"
EOF
chmod +x "$CTL"
say "Installed $CTL"

# 3. The user service ----------------------------------------------------------
mkdir -p "$UNIT_DIR"
sed -e "s|@NODE@|$NODE|g" -e "s|@PLEXO_DIR@|$PLEXO_DIR|g" \
  "$PLEXO_DIR/packaging/omarchy/$UNIT_NAME.in" >"$UNIT_DIR/$UNIT_NAME"
systemctl --user daemon-reload
systemctl --user enable "$UNIT_NAME" >/dev/null
systemctl --user restart "$UNIT_NAME" || systemctl --user start "$UNIT_NAME"
say "Service: systemctl --user status $UNIT_NAME"

# 4. The shell plugin ----------------------------------------------------------
mkdir -p "$PLUGIN_DST"
cp -f "$PLUGIN_SRC/manifest.json" "$PLUGIN_SRC/BarWidget.qml" "$PLUGIN_SRC/Panel.qml" "$PLUGIN_SRC/Plexo.js" "$PLUGIN_DST/"
say "Plugin files: $PLUGIN_DST"

if command -v omarchy >/dev/null 2>&1; then
  # Earlier names (omega.plexo, omega.braid): retire them so old widgets do
  # not linger beside oma-plexo.
  for old_id in omega.plexo omega.braid; do
    if [[ -d "$HOME/.config/omarchy/plugins/$old_id" ]]; then
      omarchy plugin disable "$old_id" >/dev/null 2>&1 || true
      rm -rf "$HOME/.config/omarchy/plugins/$old_id"
      say "Removed the old $old_id install (renamed to $PLUGIN_ID)"
    fi
  done
  omarchy plugin validate "$PLUGIN_DST" && say "Plugin manifest: valid"
  # Puts the widget in the bar and wires the shell to it; safe when it is
  # already enabled.
  omarchy plugin enable "$PLUGIN_ID" --section right >/dev/null 2>&1 ||
    say "Could not enable the plugin automatically — enable it with: omarchy plugin enable $PLUGIN_ID --section right"
fi

# 5. The system-wide helper (optional, needs sudo) -----------------------------
# One root-owned script plus a sudoers rule that lets the daemon switch the
# mode on and off through it (and run nothing else), no password. Only the
# panel's SYSTEM-WIDE INTERNET switch needs them; without this step the plugin
# still works, the switch says so.
HELPER_SRC="$PLEXO_DIR/packaging/omarchy/network/plexo-multipath"
HELPER_DST="/usr/local/libexec/plexo-multipath"
SUDOERS_FILE="/etc/sudoers.d/plexo-multipath"
HELPER_OK=0
# Up to date means: the installed script matches this checkout and the rule
# grants exactly `up` and `down` without a password.
if [[ -x "$HELPER_DST" ]] && cmp -s "$HELPER_SRC" "$HELPER_DST" &&
  sudo -n -l "$HELPER_DST" up >/dev/null 2>&1 && sudo -n -l "$HELPER_DST" down >/dev/null 2>&1; then
  HELPER_OK=1
fi
if [[ "$HELPER_OK" == 0 ]] && { sudo -n true 2>/dev/null || [[ -t 0 ]]; }; then
  say "Installing the system-wide helper (sudo)…"
  sudo install -D -m 0755 "$HELPER_SRC" "$HELPER_DST"
  TMP_RULE="$(mktemp)"
  printf '%s ALL=(root) NOPASSWD: %s up, %s down\n' "$(id -un)" "$HELPER_DST" "$HELPER_DST" >"$TMP_RULE"
  if sudo visudo -cf "$TMP_RULE" >/dev/null 2>&1; then
    sudo install -m 0440 -o root -g root "$TMP_RULE" "$SUDOERS_FILE"
    HELPER_OK=1
  else
    say "The sudoers rule did not validate; system-wide mode stays off"
  fi
  rm -f "$TMP_RULE"
fi
if [[ "$HELPER_OK" == 1 ]]; then
  say "System-wide helper: $HELPER_DST (passwordless for $(id -un), up/down only)"
else
  say "System-wide helper: not installed, or out of date. For the SYSTEM-WIDE INTERNET switch, run:"
  say "  sudo install -D -m 0755 \"$HELPER_SRC\" $HELPER_DST"
  say "  printf '%s ALL=(root) NOPASSWD: $HELPER_DST up, $HELPER_DST down\\n' \"\$(id -un)\" | sudo tee $SUDOERS_FILE >/dev/null"
  say "  sudo chmod 0440 $SUDOERS_FILE"
fi

# 6. Report ---------------------------------------------------------------------
sleep 1
if systemctl --user is-active --quiet "$UNIT_NAME"; then
  say "Daemon: running ($(systemctl --user show -p MainPID --value "$UNIT_NAME"))"
else
  say "Daemon: not running yet — journalctl --user -u $UNIT_NAME for why"
fi
say ""
say "Try it:  plexo-ctl status"
say "Panel:   click the download mark in the bar, or run: omarchy-shell shell summon $PLUGIN_ID"
